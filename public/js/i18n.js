// Get current language
function getCurrentLang() {
    return localStorage.getItem('vridhi_lang') || 'en';
}
window.getCurrentLang = getCurrentLang;

// Apply language to all data-i18n elements
function applyLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    localStorage.setItem('vridhi_lang', lang);
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
            // For input placeholders
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = TRANSLATIONS[lang][key];
            } else {
                el.textContent = TRANSLATIONS[lang][key];
            }
        }
    });
    
    // Sync all dropdown language selectors across the app
    document.querySelectorAll('.lang-select, #lang-select, #login-lang-select').forEach(selectEl => {
        if (selectEl.value !== lang) {
            selectEl.value = lang;
        }
    });

    if (window.renderQuizUI) {
        setTimeout(window.renderQuizUI, 0);
    }
    if (window.renderCategoryFilters && window.renderReportsList) {
        setTimeout(() => {
            window.renderCategoryFilters();
            window.renderReportsList();
        }, 0);
    }
    if (window.renderVideoCategoryFilters && window.renderVideoCoursesList) {
        setTimeout(() => {
            window.renderVideoCategoryFilters();
            window.renderVideoCoursesList();
            if (window.updateLearningProgressUI) window.updateLearningProgressUI();
        }, 0);
    }
    if (window.loadFinancialReport && document.getElementById('report-view') && document.getElementById('report-view').classList.contains('active')) {
        setTimeout(window.loadFinancialReport, 0);
    }
}
window.applyLanguage = applyLanguage;

// Get translation for a key
function t(key) {
    const lang = getCurrentLang();
    return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) || key;
}
window.t = t;

// Auto-apply on DOM ready
document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('vridhi_lang') || 'en';
    applyLanguage(saved);
});
